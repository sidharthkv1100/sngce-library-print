-- 1. Create the print_orders table
CREATE TABLE IF NOT EXISTS public.print_orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    token BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101),
    student_name TEXT NOT NULL,
    roll_number TEXT NOT NULL DEFAULT 'N/A',
    department TEXT NOT NULL,
    page_count INTEGER NOT NULL CHECK (page_count > 0),
    print_type TEXT NOT NULL DEFAULT 'bw',
    sides TEXT NOT NULL DEFAULT 'single',
    copies INTEGER NOT NULL DEFAULT 1 CHECK (copies > 0),
    total_fee NUMERIC(10, 2) NOT NULL CHECK (total_fee >= 0),
    pickup_slot TEXT NOT NULL,
    utr TEXT NOT NULL,
    pdf_file_name TEXT,
    pdf_file_path TEXT NOT NULL,
    payment_proof_path TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Schema Migration (run safely on already existing tables)
ALTER TABLE public.print_orders ADD COLUMN IF NOT EXISTS roll_number TEXT NOT NULL DEFAULT 'N/A';

-- Index for fast ordering and filtering by slot and status
CREATE INDEX IF NOT EXISTS idx_print_orders_created_at ON public.print_orders (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_print_orders_status ON public.print_orders (status);
CREATE INDEX IF NOT EXISTS idx_print_orders_slot ON public.print_orders (pickup_slot);

-- 2. Create the storage bucket for uploaded print documents and payment proofs
INSERT INTO storage.buckets (id, name, public)
VALUES ('print_files', 'print_files', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- 3. Row-Level Security (RLS) Configuration

-- Enable RLS on print_orders table
ALTER TABLE public.print_orders ENABLE ROW LEVEL SECURITY;

-- Permissive policies for Stage 2 testing (allows anonymous student and librarian interactions)
DROP POLICY IF EXISTS "Allow public read on print_orders" ON public.print_orders;
CREATE POLICY "Allow public read on print_orders"
ON public.print_orders FOR SELECT
TO public
USING (true);

DROP POLICY IF EXISTS "Allow public insert on print_orders" ON public.print_orders;
CREATE POLICY "Allow public insert on print_orders"
ON public.print_orders FOR INSERT
TO public
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update on print_orders" ON public.print_orders;
CREATE POLICY "Allow public update on print_orders"
ON public.print_orders FOR UPDATE
TO public
USING (true)
WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete on print_orders" ON public.print_orders;
CREATE POLICY "Allow public delete on print_orders"
ON public.print_orders FOR DELETE
TO public
USING (true);

-- Enable permissive RLS policies on storage.objects for the print_files bucket
DROP POLICY IF EXISTS "Allow public read on print_files bucket" ON storage.objects;
CREATE POLICY "Allow public read on print_files bucket"
ON storage.objects FOR SELECT
TO public
USING (bucket_id = 'print_files');

DROP POLICY IF EXISTS "Allow public insert to print_files bucket" ON storage.objects;
CREATE POLICY "Allow public insert to print_files bucket"
ON storage.objects FOR INSERT
TO public
WITH CHECK (bucket_id = 'print_files');

DROP POLICY IF EXISTS "Allow public update on print_files bucket" ON storage.objects;
CREATE POLICY "Allow public update on print_files bucket"
ON storage.objects FOR UPDATE
TO public
USING (bucket_id = 'print_files')
WITH CHECK (bucket_id = 'print_files');

DROP POLICY IF EXISTS "Allow public delete on print_files bucket" ON storage.objects;
CREATE POLICY "Allow public delete on print_files bucket"
ON storage.objects FOR DELETE
TO public
USING (bucket_id = 'print_files');

-- 4. Enable Supabase Realtime for instant cross-tab and cross-device queue updates
ALTER PUBLICATION supabase_realtime ADD TABLE public.print_orders;

